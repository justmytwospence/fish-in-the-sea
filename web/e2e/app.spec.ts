import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('session edits, explicit persistence, accessibility and unsupported state',async({page},testInfo)=>{
 await page.route('**/api/rank',route=>route.fulfill({status:503,body:JSON.stringify({error:'Test failure'}),contentType:'application/json'}));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Explore your dating market.'})).toBeVisible();
 await expect(page.getByRole('status').filter({hasText:'Updating'})).toHaveCount(0);
 await expect(page.locator('main')).toHaveAttribute('data-calculation-ready','true');
 await page.evaluate(()=>{const state=window as unknown as {longTasks:number[]};state.longTasks=[];new PerformanceObserver(list=>state.longTasks.push(...list.getEntries().map(e=>e.duration))).observe({entryTypes:['longtask']});});
 await page.getByLabel('Your age (optional)').selectOption('40');
 await expect(page.locator('main')).toHaveAttribute('data-calculation-ready','true');
 const durations=await page.evaluate(()=>(window as unknown as {longTasks:number[]}).longTasks);
 await testInfo.attach('interaction-long-tasks',{body:JSON.stringify(durations),contentType:'application/json'});
 expect(durations).toEqual([]);
 await expect.poll(()=>page.url()).toBe('http://127.0.0.1:3100/');
 await expect.poll(()=>page.evaluate(()=>localStorage.getItem('fish-in-the-sea:search'))).toBeNull();
 await page.getByRole('button',{name:'Save this search',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>localStorage.getItem('fish-in-the-sea:search'))).toContain('me=m40');
 await page.getByRole('button',{name:'Share',exact:true}).click();
 await expect(page.getByLabel('Share link preview')).toHaveValue(/v=2/);
 await page.getByRole('button',{name:'Forget saved search'}).click();
 await expect.poll(()=>page.evaluate(()=>localStorage.getItem('fish-in-the-sea:search'))).toBeNull();
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.getByText('Partner preferences (expand to edit)',{exact:true}).click();
 await page.getByText('Personal profile (optional; separate from partner preferences)',{exact:true}).click();
 const result=await new AxeBuilder({page}).analyze();
 expect(result.violations.filter(v=>v.impact==='critical'||v.impact==='serious')).toEqual([]);
 await page.screenshot({path:testInfo.outputPath('search.png'),fullPage:true});
 await page.emulateMedia({colorScheme:'dark'});
 await page.screenshot({path:testInfo.outputPath('search-dark.png'),fullPage:true});
 const dark=await new AxeBuilder({page}).analyze();
 expect(dark.violations.filter(v=>v.impact==='critical'||v.impact==='serious')).toEqual([]);
 if(testInfo.project.name==='desktop') { await page.evaluate(()=>{document.body.style.zoom='2';}); await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1); await page.screenshot({path:testInfo.outputPath('search-zoom.png'),fullPage:true}); }
 await page.evaluate(()=>{document.body.style.zoom='1';});
 await page.goto('/?v=2&me=m36&seek=f40-60&f=kw0');
 await expect(page.getByRole('alert',{name:'Unsupported search'})).toContainText('18–49');
 await page.getByRole('button',{name:'Remove kids-someday filter'}).click();
 await expect(page.locator('main')).toHaveAttribute('data-calculation-ready','true');
 await expect(page.getByRole('alert',{name:'Unsupported search'})).toHaveCount(0);
});
test('keyboard place search and saved link loading',async({page})=>{
 await page.goto('/?v=2&me=f30&seek=m28-40');
 const search=page.getByRole('combobox',{name:'City or metro area'});
 await search.fill('Chicago');
 await expect(page.getByRole('listbox',{name:'City or metro area'}).getByRole('option').first()).toBeVisible();
 await search.press('ArrowDown');await search.press('Enter');
 await expect(page.getByRole('region',{name:'Search summary'})).toContainText('Chicago');
 await expect(page.getByRole('status').filter({hasText:'Previous results'})).toHaveCount(0);
});
